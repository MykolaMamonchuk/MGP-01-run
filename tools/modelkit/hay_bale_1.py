"""Тюк сіна за малюнком hay_bale_1.png: кругла солом'яна куля з «пластівців» соломи,
перехоплена чотирма брунатними ременями навхрест. Траву-підставку, камінець і квіточки на траві
не моделюємо (у мірі вони замальовані полем erase).

Перешкода, що котиться: діаметр 0,62 м, початок у центрі дна, ремені (4 см завширшки) виступають на 0,9 см.
Геометрія — haybale_common."""
import haybale_common as hc

PAL = {
    # Кластери малюнка (#B3701C, #DBA532, #F4CE5D, #FCEA7F; ремені #865922/#55340D), тоновані під
    # світло заміру: PAL ≈ 0,8 · (сер + 1,25 · (колір − сер)).
    "straw_lo": "#9E5B07", "straw": "#BE8815", "straw_hi": "#D0AA39", "straw_top": "#D3C156",
    "straw_seam": "#A86C12",
    "band_lo": "#5E3808", "band": "#7E5018", "band_hi": "#906228",
}

R = 0.31
# ремені: (нахил осі від вертикалі, поворот осі навколо вертикалі) — великі кола кулі
BANDS = [(58, 35), (58, 150), (80, 95), (18, 10)]


def materials(k):
    return {
        "straw": hc.mat_straw("straw", flakes=11.0, seam_w=0.03),
        # ремінь — рівний шкіряний, темніший лише до країв (не кручена мотузка)
        "band": k.mat_gradient("band", [(0.0, "band_lo"), (0.5, "band"), (1.0, "band_hi")], 0.0, 2 * R, 0.3, 5.0),
    }


def build(m, k):
    hc.ball("body", m["straw"], k, R)
    for i, (tilt, turn) in enumerate(BANDS):
        hc.ring("band%d" % i, m["band"], k, (0, 0, R), R, 0.009, hc.axis_from(tilt, turn), flat=2.3)
    return {}
